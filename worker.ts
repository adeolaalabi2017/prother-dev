/**
 * Custom Worker entry: an edge HTML/OG cache in front of the OpenNext handler.
 *
 * Why this exists: a Worker runs BEFORE Cloudflare's CDN cache, so the
 * `s-maxage` / `stale-while-revalidate` headers set in next.config.ts never
 * make the CDN serve a copy. Every crawler hit and page view was a full SSR
 * render. On the Workers Free plan (10ms CPU per request) that rendering
 * (p50 ~45ms) exhausted the CPU allowance during bot bursts and requests died
 * with `exceededResources` (served as 503).
 *
 * This wrapper stores cacheable responses in the per-colo Cache API
 * (`caches.default`) and serves them without invoking Next at all. It honors
 * the policy Next already emits: only `public` responses with `s-maxage > 0`
 * and no `Set-Cookie` are stored. Stale entries (inside the
 * stale-while-revalidate window) are served immediately and refreshed in the
 * background.
 *
 * Bypassed entirely for: non-GET, signed-in visitors (session cookie), RSC /
 * router requests, /admin, and /api/* except /api/og.
 *
 * Note: the Cache API is a no-op on *.workers.dev; it works on prother.dev.
 */
// @ts-ignore - generated by `opennextjs-cloudflare build`
import handler from "./.open-next/worker.js";

// Durable Object classes must be re-exported from the entry module.
// @ts-ignore - generated by `opennextjs-cloudflare build`
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "./.open-next/worker.js";

/** `caches.default` is Workers-only; typed locally so tsc does not need workers-types. */
function edgeCache(): Cache {
  return (caches as unknown as { default: Cache }).default;
}

type Ctx = { waitUntil(p: Promise<unknown>): void; passThroughOnException?(): void };

/** /api/og renders a share image with satori: expensive, and rarely changes. */
const OG_POLICY = { sMaxAge: 86_400, swr: 604_800 };

const SESSION_COOKIE = /(?:^|;\s*)(?:__Secure-)?(?:next-auth|authjs)\.session-token/;
const TRACKING_PARAMS = /^(utm_|fbclid$|gclid$|msclkid$|mc_eid$|ref$)/;
// Bookkeeping headers kept on the stored copy only (stripped before serving).
const CACHED_AT = "x-edge-cached-at";
const FRESH_FOR = "x-edge-fresh-for";
const CLIENT_CC = "x-edge-client-cc";

function isCacheableRequest(req: Request, url: URL): boolean {
  if (req.method !== "GET") return false;
  const p = url.pathname;
  if (p.startsWith("/admin")) return false;
  if (p.startsWith("/api/") && p !== "/api/og") return false;
  if (url.searchParams.has("_rsc")) return false;
  const h = req.headers;
  if (h.has("rsc") || h.has("next-router-state-tree") || h.has("next-router-prefetch") || h.has("next-action")) {
    return false;
  }
  if (SESSION_COOKIE.test(h.get("cookie") ?? "")) return false;
  return true;
}

/** Normalized cache key: drop tracking params so they share one entry. */
function cacheKey(url: URL): Request {
  const k = new URL(url.toString());
  for (const name of [...k.searchParams.keys()]) {
    if (TRACKING_PARAMS.test(name)) k.searchParams.delete(name);
  }
  k.searchParams.sort();
  k.hash = "";
  return new Request(k.toString(), { method: "GET" });
}

/** Parse the shared-cache policy from a response, or null if not storable. */
function policyFor(url: URL, res: Response): { sMaxAge: number; swr: number } | null {
  if (res.status !== 200 || res.headers.has("set-cookie")) return null;
  if (url.pathname === "/api/og") {
    return (res.headers.get("content-type") ?? "").startsWith("image/") ? OG_POLICY : null;
  }
  const cc = (res.headers.get("cache-control") ?? "").toLowerCase();
  if (!/\bpublic\b/.test(cc) || /\b(no-store|private)\b/.test(cc)) return null;
  const sMaxAge = Number(/s-maxage=(\d+)/.exec(cc)?.[1] ?? 0);
  if (!sMaxAge) return null;
  const swr = Number(/stale-while-revalidate=(\d+)/.exec(cc)?.[1] ?? 0);
  return { sMaxAge, swr };
}

async function renderAndStore(
  req: Request,
  url: URL,
  key: Request,
  env: unknown,
  ctx: Ctx,
): Promise<Response> {
  const res: Response = await handler.fetch(req, env, ctx);
  const policy = policyFor(url, res);
  if (!policy) return res;

  const out = new Response(res.body, res);
  if (url.pathname === "/api/og") {
    out.headers.set(
      "cache-control",
      `public, max-age=3600, s-maxage=${policy.sMaxAge}, stale-while-revalidate=${policy.swr}`,
    );
  }

  const stored = new Response(out.clone().body, out);
  stored.headers.delete("vary"); // the key already isolates RSC/router variants
  stored.headers.set(CACHED_AT, String(Date.now()));
  stored.headers.set(FRESH_FOR, String(policy.sMaxAge));
  stored.headers.set(CLIENT_CC, out.headers.get("cache-control") ?? "");
  // Cache API eviction horizon = fresh window + stale window.
  stored.headers.set("cache-control", `public, max-age=${policy.sMaxAge + policy.swr}`);
  ctx.waitUntil(edgeCache().put(key, stored));

  out.headers.set("x-edge-cache", "MISS");
  return out;
}

export default {
  async fetch(req: Request, env: unknown, ctx: Ctx): Promise<Response> {
    const url = new URL(req.url);
    if (!isCacheableRequest(req, url)) return handler.fetch(req, env, ctx);

    const key = cacheKey(url);
    let hit: Response | undefined;
    try {
      hit = await edgeCache().match(key);
    } catch {
      hit = undefined;
    }
    if (!hit) return renderAndStore(req, url, key, env, ctx);

    const cachedAt = Number(hit.headers.get(CACHED_AT) ?? 0);
    const freshFor = Number(hit.headers.get(FRESH_FOR) ?? 0);
    const ageSec = Math.max(0, Math.floor((Date.now() - cachedAt) / 1000));

    const out = new Response(hit.body, hit);
    out.headers.set("cache-control", hit.headers.get(CLIENT_CC) || "public, max-age=0");
    for (const h of [CACHED_AT, FRESH_FOR, CLIENT_CC]) out.headers.delete(h);
    out.headers.set("age", String(ageSec));

    if (ageSec > freshFor) {
      out.headers.set("x-edge-cache", "STALE");
      // Refresh in the background; the visitor gets the stale copy now.
      ctx.waitUntil(renderAndStore(req.clone(), url, key, env, ctx).catch(() => undefined));
    } else {
      out.headers.set("x-edge-cache", "HIT");
    }
    return out;
  },
};
